"""Quantify independent CVSX agreement using archived outputs, with no fitting."""
import hashlib
import json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"reports/m3-source-audit"


def main():
    OUT.mkdir(exist_ok=True)
    comparisons=[]
    fig,axs=plt.subplots(2,2,figsize=(11,7),layout="constrained")
    cases=[("baseline","reports/m3-sweeps/baseline"),
           ("thoracic_zero","reports/m3-sweep-repairs-thoracic/thoracic_zero")]
    for row,(name,ours) in enumerate(cases):
        own=ROOT/ours
        other=ROOT/"reports/m3-cvsx"/name
        a=np.load(own/"trajectory.npz")
        b=np.load(other/"trajectory.npz")
        metrics=json.loads((own/"result.json").read_text())["metrics"]["mean"]
        bm=json.loads((other/"result.json").read_text())
        mask=b["time_s"]>=112.5
        t=b["time_s"][mask]
        for node in ("lv","rv"):
            v=b["state_v_"+node][mask]*1000
            bm[node.upper()+"_EDV_mL"]=float(v.max())
            bm[node.upper()+"_ESV_mL"]=float(v.min())
            bm[node.upper()+"_SV_mL"]=float(np.ptp(v))
        bm["RV_output_L_min"]=float(np.trapezoid(b["q_pv"][mask],t)/7.5*60)
        for node in ("vc","pu"):
            bm[node.upper()+"_mean_mmHg"]=float(np.trapezoid(b["p_"+node][mask],t)/7.5)
        bm["PA_systolic_mmHg"]=float(b["p_pa"][mask].max())
        bm["PA_diastolic_mmHg"]=float(b["p_pa"][mask].min())
        deltas={k:100*abs(bm[k]-v)/abs(v) for k,v in metrics.items()}
        # Both drivers share t mod .75: align by known phase, no optimized lag.
        phase=np.linspace(0,.75,1501)
        own_time=a["time_s"][-1]-.75+phase
        ref_time=b["time_s"][-1]-.75+phase
        waveforms={}
        for i,node in enumerate(("LV","RV","AO","VC","PA","PU")):
            for key,ov,rv,unit in (
                ("P_"+node,a["pressures_mmHg"][:,i],b["p_"+node.lower()],"mmHg"),
                ("V_"+node,a["states"][i],b["state_v_"+node.lower()]*1000,"mL")):
                x=np.interp(own_time,a["time_s"],ov)
                y=np.interp(ref_time,b["time_s"],rv)
                waveforms[key]={"maximum_absolute_difference":float(np.max(abs(x-y))),
                    "rms_difference":float(np.sqrt(np.mean((x-y)**2))),"unit":unit}
                if key in ("P_AO","V_LV"):
                    ax=axs[row,0 if key=="P_AO" else 1]
                    ax.plot(phase,x,label="Project Radau",lw=2)
                    ax.plot(phase,y,"--",label="CVSX Tsit5",lw=1)
                    ax.set(xlabel="Cardiac phase (s)",ylabel=f"{key} ({unit})",title=name)
                    ax.legend()
        comparisons.append({"case":name,"project":metrics,"CVSX":bm,
                            "relative_metric_difference_pct":deltas,"waveforms":waveforms,
                            "within_predeclared_1pct":max(deltas.values())<1})
    fig.savefig(OUT/"independent-waveforms.png",dpi=160)
    plt.close(fig)
    frozen=json.loads((ROOT/"data/m2-freeze-manifest.json").read_text())["sha256"]
    hashes={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest()==h for p,h in frozen.items()}
    source_hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest()==hashlib.sha256(
        (ROOT/"references/m3/cvsx-upstream/cvsx"/p.name).read_bytes()).hexdigest()
        for p in (ROOT/"references/m2/cvsx").glob("*.py") if p.name!="generate_paper_plots.py"}
    result={"comparisons":comparisons,"frozen_hashes_unchanged":hashes,
            "pinned_CVSX_subset_identical":source_hashes}
    (OUT/"comparison.json").write_text(json.dumps(result,indent=2)+"\n")
    lines=["# Independent source comparison", "", "2026-10-04. Generated by `scripts/report_m3_source_audit.py`.","",
           "| Case | Project CO (L/min) | CVSX CO (L/min) | Largest difference across 15 metrics (%) | 1% screen |",
           "|---|---:|---:|---:|---|"]
    for c in comparisons:
        lines.append(f'| {c["case"]} | {c["project"]["CO_L_min"]:.8f} | {c["CVSX"]["CO_L_min"]:.8f} | '
                     f'{max(c["relative_metric_difference_pct"].values()):.6f} | {c["within_predeclared_1pct"]} |')
    drop=100*(1-comparisons[1]["CVSX"]["CO_L_min"]/comparisons[0]["CVSX"]["CO_L_min"])
    lines += ["",f"Independent CVSX decrease: **{drop:.6f}%**. The manuscript's 9±5-point screen still fails.","",
        "![Same-phase independent waveform comparison](independent-waveforms.png)","",
        "The curves use their last complete cycle, aligned by the common 0.75-second driver phase; no fitted time lag. "
        "All six volume and pressure waveform errors are recorded in comparison.json. "
        "Metrics compare project ten-cycle averages with CVSX's ten-cycle mean flows and window extrema; small residual drift and sampling differences remain.","",
        "CVSX commit 6e7d6a224e7c6afda4227c46b6c450a973fd5d2a is unmodified, with a separate adapter. "
        "Its fixed-state clipped valve law and Newton septal solver differ from our event-reset valves and Brent root solver. "
        "Diffrax Tsit5 uses x64, rtol 1e-8, atol 1e-11 in litres/second-based states, max step 1 ms, "
        "112.5 seconds warm-up and 7.5 seconds measurement sampled every 0.5 ms. "
        "L_mt alone is explicitly matched from upstream 7.6967e-5 to pinned CellML 7.6968e-5 mmHg s²/mL. "
        "No project RHS is imported. Last-cycle phase differences pass 1e-5; all recorded inventories conserve volume.","",
        "The separate Python 3.12 environment retains upstream Diffrax 0.4.1 and Equinox 0.10.11. "
        "NumPy 1.26.4 replaces upstream's ~1.25.2 requirement for Python 3.12 wheels; this is not an exact historical dependency reproduction. "
        "requirements-cvsx.txt and each run's manifest pin actual packages. Refinement runs at rtol 1e-9 are archived separately.","",
        f"All nine frozen M2 files unchanged: {all(hashes.values())}. Pinned CVSX subset identical: {all(source_hashes.values())}.","",
        "See [investigation](investigation.md) for source provenance, model-form tests and remaining work.",""]
    (OUT/"report.md").write_text("\n".join(lines),encoding="utf-8")
    print(json.dumps({"max_metric_difference_pct":max(max(c["relative_metric_difference_pct"].values()) for c in comparisons),
                      "CVSX_drop_pct":drop,"frozen_unchanged":all(hashes.values())}))


if __name__=="__main__": main()
